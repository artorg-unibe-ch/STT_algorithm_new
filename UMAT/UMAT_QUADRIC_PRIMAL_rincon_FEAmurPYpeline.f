C  * U S E R   M A T E R I A L    
C
C     PROPS(1)  - FLAG FOR PARAMETER SELECTION
C                 0 - TRABECULAR BONE ISOTROPIC
C                 1 - TRABECULAR BONE TRANSVERSELY ISOTROPIC
C                 2 - TRABECULAR BONE FABRIC-BASED ORTHOTROPIC
C                 3 - COMPACT BONE ISOTROPIC
C                 4 - COMPACT BONE TRANSVERSELY ISOTROPIC
C     PROPS(2)  - BV/TV
C     PROPS(3)  - M1
C     PROPS(4)  - M2
C     PROPS(5)  - M3
C     PROPS(6)  - DENSFL
C     PROPS(7)  - VISCFL
C     PROPS(8)  - PYFL
C
C     HARD WIRED FLAGS:
C
C     DENSIFICATOR FLAG: 0 - DENSIFICATION OFF
C                        1 - DENSIFICATION ON
C     VISCOSITY FLAG:    0 - RATE-INDEPENDENT
C                        1 - LINEAR VISCOSITY
C                        2 - EXPONENTIAL VISC
C                        3 - LOGARITHMIC VISC
C                        4 - POLYNOMIAL VISC
C                        5 - POWER LAW VISC 
C     POSTYIELD FLAG:    0 - PERFECT PLASTICITY
C                        1 - EXPONENTIAL HARDENING
C                        2 - SIMPLE SOFTENING
C                        3 - EXPONENTIAL SOFTENING
C                        4 - PIECEWISE SOFTENING
C
C  M E D T O O L  T E M P L A T E 
C     ** XXX to be replaced by user -> Bone flag
C     ** CardName BVTV, EigVal.., replace by medtool 
C     *MATERIAL, NAME=CardName
C     *DEPVAR
C     22
C     *USER MATERIAL, CONSTANTS=5, UNSYMM
C     XXX, BVTV, EigVal3, EigVal2,  EigVal1
